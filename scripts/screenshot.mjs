import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => console.log('PAGEERROR', error.message));
page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE', message.text().slice(0, 300)); });
await page.goto('http://127.0.0.1:5174');
await page.waitForTimeout(3000);
await page.screenshot({ path: '/private/tmp/tiex-menu.png' });
console.log(await page.evaluate(() => ({ mode: window.__TIEX__?.mode, fps: window.__TIEX__?.fps, calls: window.__TIEX__?.sceneManager.renderer.info.render.calls, triangles: window.__TIEX__?.sceneManager.renderer.info.render.triangles })));
await page.click('#new-game');
await page.click('#skip-cinematic');
await page.waitForTimeout(1500);
await page.screenshot({ path: '/private/tmp/tiex-game.png' });
console.log(await page.evaluate(() => ({ mode: window.__TIEX__?.mode, fps: window.__TIEX__?.fps, calls: window.__TIEX__?.sceneManager.renderer.info.render.calls })));
await page.keyboard.down('KeyW');
await page.waitForTimeout(1800);
await page.keyboard.up('KeyW');
console.log(await page.evaluate(() => ({ position: window.__TIEX__?.state.position, flags: window.__TIEX__?.state.flags })));
await browser.close();
